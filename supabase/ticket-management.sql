create table if not exists public.tickets (
  id uuid primary key default gen_random_uuid(),
  number bigint generated by default as identity (start with 1001) unique,
  title text not null,
  description text not null default '',
  category text not null,
  team_id uuid,
  team_name text,
  priority text not null default 'medium' check (priority in ('highest', 'high', 'medium', 'low', 'lowest')),
  status text not null default 'open' check (status in ('open', 'in_progress', 'on_hold', 'review', 'closed')),
  raised_by uuid not null default auth.uid(),
  raised_by_name text not null,
  raised_by_email text,
  assignee_id text,
  assignee_name text,
  assignee_email text,
  due_date timestamptz not null,
  -- SLA: while On Hold the clock is paused; leaving On Hold pushes due_date forward.
  sla_paused_at timestamptz,
  sla_warned_at timestamptz,
  escalation_level smallint not null default 0,
  escalated_at timestamptz,
  review_requested_at timestamptz,
  closed_at timestamptz,
  reopened_count integer not null default 0,
  rating smallint check (rating between 1 and 5),
  rating_comment text,
  rated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Databases created earlier only allow high / medium / low: allow Highest, High, Medium, Low, Lowest.
-- Existing tickets keep their level (high stays High, and so on). Safe to run again.
do $$
declare
  c record;
begin
  for c in
    select conname
    from pg_constraint
    where conrelid = 'public.tickets'::regclass
      and contype = 'c'
      and pg_get_constraintdef(oid) ilike '%priority%'
  loop
    execute format('alter table public.tickets drop constraint %I', c.conname);
  end loop;
  alter table public.tickets
    add constraint tickets_priority_check check (priority in ('highest', 'high', 'medium', 'low', 'lowest'));
end $$;

