create or replace function public.ticket_before_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    if new.status = 'on_hold' then new.sla_paused_at := now(); end if;
    return new;
  end if;

  new.updated_at := now();
  -- The requester and ticket number never change.
  new.raised_by := old.raised_by;
  new.number := old.number;

  -- Only the requester can rate.
  if new.rating is distinct from old.rating and auth.uid() is not null and auth.uid() <> old.raised_by then
    raise exception 'Only the person who raised the ticket can rate it';
  end if;
  if new.rating is distinct from old.rating then new.rated_at := now(); end if;

  if new.status is distinct from old.status then
    -- SLA pause / resume.
    if new.status = 'on_hold' then
      new.sla_paused_at := now();
    elsif old.status = 'on_hold' and old.sla_paused_at is not null then
      new.due_date := old.due_date + (now() - old.sla_paused_at);
      new.sla_paused_at := null;
    end if;

    if new.status = 'review' then new.review_requested_at := now(); end if;
    if new.status = 'closed' then new.closed_at := now(); end if;

    if old.status in ('review', 'closed') and new.status in ('open', 'in_progress', 'on_hold') then
      new.reopened_count := old.reopened_count + 1;
      new.closed_at := null;
      new.review_requested_at := null;
      new.rating := null;
      new.rating_comment := null;
      new.rated_at := null;
    end if;
  end if;

  -- A new due date restarts warnings and escalation.
  if new.due_date is distinct from old.due_date and new.due_date > now() then
    new.sla_warned_at := null;
    new.escalation_level := 0;
    new.escalated_at := null;
  end if;

  return new;
end;
$$;

drop trigger if exists tickets_before_write on public.tickets;
create trigger tickets_before_write
before insert or update on public.tickets
for each row execute function public.ticket_before_write();

create or replace function public.ticket_status_label(value text)
returns text
language sql
immutable
as $$
  select case value
    when 'open' then 'Open'
    when 'in_progress' then 'In Progress'
    when 'on_hold' then 'On Hold'
    when 'review' then 'Review'
    when 'closed' then 'Closed'
    else value end;
$$;

create or replace function public.ticket_after_write()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  actor text := public.ticket_actor_name();
  label text := 'TKT-' || new.number;
begin
  if tg_op = 'INSERT' then
    insert into public.ticket_activity (ticket_id, actor_name, text) values (new.id, actor, 'created this ticket');
    if new.assignee_name is not null then
      insert into public.ticket_activity (ticket_id, actor_name, text) values (new.id, actor, 'assigned to ' || new.assignee_name);
      perform public.ticket_notify(new.id, array[new.assignee_email], 'assigned',
        'New ticket ' || label || ' assigned to you', new.raised_by_name || ': ' || new.title);
    else
      -- Nobody picked yet: let admin and HR know a ticket was raised.
      perform public.ticket_notify(new.id, public.ticket_staff_emails(), 'raised',
        'New ticket ' || label || ' raised', new.raised_by_name || ': ' || new.title);
    end if;
    return new;
  end if;

  if new.status is distinct from old.status then
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (new.id, actor, 'moved to ' || public.ticket_status_label(new.status));
    if new.status = 'review' then
      perform public.ticket_notify(new.id, array[new.raised_by_email], 'review',
        label || ' is ready for your review', 'Please confirm whether your issue is solved.');
      perform public.ticket_notify(new.id, public.ticket_participants(new.id, false), 'status',
        label || ' moved to Review', new.title);
    else
      perform public.ticket_notify(new.id, public.ticket_participants(new.id), 'status',
        label || ' moved to ' || public.ticket_status_label(new.status), new.title);
    end if;
  end if;

  if new.assignee_id is distinct from old.assignee_id then
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (new.id, actor, coalesce('assigned to ' || new.assignee_name, 'cleared Assigned to'));
    perform public.ticket_notify(new.id, array[new.assignee_email], 'assigned', label || ' assigned to you', new.title);
  end if;

  if new.priority is distinct from old.priority then
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (new.id, actor, 'changed priority to ' || initcap(new.priority));
  end if;

  if new.due_date is distinct from old.due_date and not (old.status = 'on_hold' and new.status <> 'on_hold') then
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (new.id, actor, 'changed due date to ' || to_char(new.due_date at time zone 'Asia/Kolkata', 'DD Mon YYYY'));
  end if;

  if new.team_id is distinct from old.team_id then
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (new.id, actor, coalesce('routed to ' || new.team_name, 'cleared the sub category'));
  end if;

  if new.rating is distinct from old.rating and new.rating is not null then
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (new.id, actor, 'rated the support ' || new.rating || '/5');
  end if;

  if new.title is distinct from old.title or new.description is distinct from old.description or new.category is distinct from old.category then
    insert into public.ticket_activity (ticket_id, actor_name, text) values (new.id, actor, 'updated ticket details');
  end if;

  return new;
end;
$$;

drop trigger if exists tickets_after_write on public.tickets;
create trigger tickets_after_write
after insert or update on public.tickets
for each row execute function public.ticket_after_write();

create or replace function public.ticket_watchers_after_change()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  t public.tickets;
begin
  if tg_op = 'INSERT' then
    select * into t from public.tickets where id = new.ticket_id;
    insert into public.ticket_activity (ticket_id, actor_name, text) values (new.ticket_id, public.ticket_actor_name(), 'added ' || new.name);
    perform public.ticket_notify(new.ticket_id, array[new.email], 'added', 'You were added to TKT-' || t.number, t.title);
    return new;
  end if;
  -- When the whole ticket is being deleted this row is removed by cascade; the ticket is already
  -- gone, so logging activity for it would violate ticket_activity_ticket_id_fkey.
  if exists (select 1 from public.tickets where id = old.ticket_id) then
    insert into public.ticket_activity (ticket_id, actor_name, text) values (old.ticket_id, public.ticket_actor_name(), 'removed ' || old.name);
  end if;
  return old;
end;
$$;

drop trigger if exists ticket_watchers_after_change on public.ticket_watchers;
create trigger ticket_watchers_after_change
after insert or delete on public.ticket_watchers
for each row execute function public.ticket_watchers_after_change();

-- Comments notify everyone on the ticket (internal notes skip the requester) and
-- @mentioned people, who are also added to the ticket.
create or replace function public.ticket_comments_after_insert()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  t public.tickets;
  m jsonb;
  mentioned text[] := '{}';
begin
  select * into t from public.tickets where id = new.ticket_id;
  update public.tickets set updated_at = now() where id = new.ticket_id;

  for m in select * from jsonb_array_elements(coalesce(new.mentions, '[]'::jsonb)) loop
    if coalesce(m ->> 'id', '') <> '' then
      insert into public.ticket_watchers (ticket_id, person_id, name, email)
      values (new.ticket_id, m ->> 'id', coalesce(m ->> 'name', 'Employee'), nullif(m ->> 'email', ''))
      on conflict do nothing;
      if coalesce(m ->> 'email', '') <> '' then
        mentioned := mentioned || lower(m ->> 'email');
      end if;
    end if;
  end loop;

  perform public.ticket_notify(new.ticket_id, mentioned, 'mention',
    new.author_name || ' mentioned you on TKT-' || t.number, left(new.body, 140));

  perform public.ticket_notify(
    new.ticket_id,
    array(
      select e from unnest(public.ticket_participants(new.ticket_id, not new.is_internal)) e
      where e is not null and not (e = any (mentioned))
    ),
    'comment',
    case when new.is_internal then 'Internal note on TKT-' else 'New comment on TKT-' end || t.number,
    new.author_name || ': ' || left(new.body, 140)
  );
  return new;
end;
$$;

drop trigger if exists ticket_comments_after_insert on public.ticket_comments;
create trigger ticket_comments_after_insert
after insert on public.ticket_comments
for each row execute function public.ticket_comments_after_insert();

