create or replace function public.ticket_my_email()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select lower(coalesce(
    nullif(auth.jwt() ->> 'email', ''),
    (select p.email from public.profiles p where p.id = auth.uid())
  ));
$$;

create or replace function public.ticket_actor_name()
returns text
language sql
stable
security definer
set search_path = public
as $$
  select coalesce((select p.name from public.profiles p where p.id = auth.uid()), 'System');
$$;

