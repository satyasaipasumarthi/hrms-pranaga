-- Everything else (ticket_notify, ticket_staff_emails, triggers, ...) is internal: no direct access.

-- ------------------------------------------------------------
-- Realtime (live board + notification bell)
-- ------------------------------------------------------------

do $$
declare
  tbl text;
begin
  foreach tbl in array array['tickets', 'ticket_comments', 'ticket_watchers', 'ticket_attachments', 'ticket_activity', 'ticket_notifications']
  loop
    begin
      execute format('alter publication supabase_realtime add table public.%I', tbl);
    exception when duplicate_object then null;
    end;
  end loop;
end $$;

