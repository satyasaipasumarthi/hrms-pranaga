-- Inserts one notification per distinct e-mail, skipping the person who caused it.
create or replace function public.ticket_notify(
  target uuid,
  recipients text[],
  notif_kind text,
  notif_title text,
  notif_body text default null
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  actor text := public.ticket_my_email();
begin
  insert into public.ticket_notifications (recipient_email, ticket_id, kind, title, body)
  select distinct lower(r), target, notif_kind, notif_title, notif_body
  from unnest(recipients) as r
  where r is not null and r <> '' and lower(r) is distinct from actor;
end;
$$;

-- Raiser, assignee and watchers of a ticket.
create or replace function public.ticket_participants(target uuid, include_requester boolean default true)
returns text[]
language sql
stable
security definer
set search_path = public
as $$
  select array_remove(array_agg(distinct lower(e)), null)
  from (
    select case when include_requester then t.raised_by_email end as e from public.tickets t where t.id = target
    union all
    select t.assignee_email from public.tickets t where t.id = target
    union all
    select w.email from public.ticket_watchers w where w.ticket_id = target
  ) s;
$$;

create or replace function public.ticket_staff_emails()
returns text[]
language sql
stable
security definer
set search_path = public
as $$
  select coalesce(array_agg(lower(p.email)), '{}')
  from public.profiles p
  where p.role in ('admin', 'hr') and coalesce(p.is_active, true);
$$;

