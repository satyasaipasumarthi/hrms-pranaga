-- Every active employee (name + email only) for "Add people" and @mentions.
create or replace function public.ticket_directory()
returns table (id uuid, name text, email text, role text)
language sql
stable
security definer
set search_path = public
as $$
  select p.id, p.name, p.email, p.role
  from public.profiles p
  where coalesce(p.is_active, true)
  order by p.name;
$$;

-- Onboarded employees whose department matches a team (assignee list).
create or replace function public.ticket_team_employees(departments text[])
returns table (id uuid, name text, email text, designation text, department text)
language sql
stable
security definer
set search_path = public
as $$
  select e.id,
         trim(coalesce(e.first_name, '') || ' ' || coalesce(e.last_name, '')),
         coalesce(nullif(e.business_email, ''), e.personal_email),
         e.designation,
         e.department
  from public.employee_onboarding e
  where lower(e.department) = any (select lower(d) from unnest(departments) d)
  order by e.first_name;
$$;

