-- SLA warnings (75% of time used), escalation when overdue, auto-close of tickets left
-- in Review for 3 days. Schedule it with pg_cron (below);
-- the app also calls it when the Tickets page opens.
create or replace function public.run_ticket_automation()
returns json
language plpgsql
security definer
set search_path = public
as $$
declare
  r record;
  warned int := 0;
  escalated int := 0;
  closed int := 0;
begin
  -- 1. SLA warning at 75% of the allowed time.
  for r in
    select * from public.tickets
    where status not in ('review', 'closed', 'on_hold')
      and sla_warned_at is null
      and now() < due_date
      and now() >= created_at + (due_date - created_at) * 0.75
  loop
    update public.tickets set sla_warned_at = now() where id = r.id;
    perform public.ticket_notify(r.id, array[r.assignee_email, r.raised_by_email], 'sla',
      'TKT-' || r.number || ' is close to its due date', r.title);
    warned := warned + 1;
  end loop;

  -- 2. Escalation: level 1 when overdue, level 2 when overdue by the full SLA again.
  for r in
    select * from public.tickets
    where status not in ('review', 'closed', 'on_hold')
      and now() > due_date
      and (escalation_level = 0 or (escalation_level = 1 and now() > due_date + (due_date - created_at)))
  loop
    update public.tickets set escalation_level = r.escalation_level + 1, escalated_at = now() where id = r.id;
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (r.id, 'System', 'escalated (level ' || (r.escalation_level + 1) || ') – due date passed');
    perform public.ticket_notify(r.id, array[r.assignee_email] || public.ticket_staff_emails(), 'escalation',
      'TKT-' || r.number || ' escalated: overdue', r.title);
    escalated := escalated + 1;
  end loop;

  -- 3. Auto-close tickets the requester did not confirm within 3 days.
  for r in
    select * from public.tickets
    where status = 'review' and review_requested_at < now() - interval '3 days'
  loop
    update public.tickets set status = 'closed' where id = r.id;
    insert into public.ticket_activity (ticket_id, actor_name, text)
    values (r.id, 'System', 'auto-closed after 3 days in Review without a reply');
    closed := closed + 1;
  end loop;

  return json_build_object('warned', warned, 'escalated', escalated, 'auto_closed', closed);
end;
$$;

-- ------------------------------------------------------------
-- Lock down function access.
-- Supabase gives EXECUTE on every new function to `anon` (people who are NOT logged in) and
-- the public app key is visible in the website, so without this anyone could read the
-- employee list or admin e-mails, or create notifications. Revoke everything first, then
-- grant back only what a logged-in browser needs.
-- ------------------------------------------------------------

drop function if exists public.ticket_is_requester_only(uuid);
drop function if exists public.ticket_workload(text[]);
drop function if exists public.ticket_merge(uuid, uuid);

do $$
declare
  f record;
begin
  for f in
    select p.oid::regprocedure as sig
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public'
      and (p.proname like 'ticket%' or p.proname in ('can_view_ticket_id', 'can_edit_ticket_id', 'run_ticket_automation'))
  loop
    execute format('revoke all on function %s from public, anon, authenticated', f.sig);
  end loop;
end $$;

