-- ============================================================
-- [ticket-management] Ticket Management backend
-- Run once in the Supabase SQL editor (safe to re-run).
--
-- Creates: tickets + comments, attachments (Storage bucket), watchers ("Add people"),
-- activity log, links, notifications, saved views,
-- SLA / escalation / auto-close automation, and the RPCs the app calls.
--
-- Who can SEE a ticket: every signed-in user (employees, managers, HR, admin).
-- Who can CHANGE one (edit, comment, attach, add people): admin, HR and managers, plus the person
-- who raised it, the person it is assigned to, and people added to it. Internal notes are visible
-- only to admin / HR / managers, the assigned person and added people.
-- People from employee_onboarding are matched to logins by e-mail (their row id is not the login id).
-- ============================================================

create extension if not exists pgcrypto;

