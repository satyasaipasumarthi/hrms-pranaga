-- Who may see a ticket: admin / HR / manager see all; everyone else only tickets they raised,
-- are assigned to, or were added to (same people who can edit it).
create or replace function public.can_view_ticket_id(target uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select auth.uid() is not null and public.can_edit_ticket_id(target);
$$;

-- Who may change a ticket: admin / HR / manager, the requester, the assigned person, or added people.
create or replace function public.can_edit_ticket_id(target uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.tickets t
    where t.id = target
      and (
        public.ticket_is_manager()
        or t.raised_by = auth.uid()
        or t.assignee_id = auth.uid()::text
        or lower(t.assignee_email) = public.ticket_my_email()
        or exists (
          select 1 from public.ticket_watchers w
          where w.ticket_id = t.id
            and (w.person_id = auth.uid()::text or lower(w.email) = public.ticket_my_email())
        )
      )
  );
$$;

-- Internal notes: admin / HR / managers, the assigned person and added people only.
create or replace function public.ticket_can_see_internal(target uuid)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.tickets t
    where t.id = target
      and (
        public.ticket_is_manager()
        or t.assignee_id = auth.uid()::text
        or lower(t.assignee_email) = public.ticket_my_email()
        or exists (
          select 1 from public.ticket_watchers w
          where w.ticket_id = t.id
            and (w.person_id = auth.uid()::text or lower(w.email) = public.ticket_my_email())
        )
      )
  );
$$;

